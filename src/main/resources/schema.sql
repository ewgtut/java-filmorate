CREATE TABLE IF NOT EXISTS RATING(
  ID int not null GENERATED BY DEFAULT AS IDENTITY ,
  NAME varchar(100) not null,
  CONSTRAINT rating_id PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS GENRE(
  ID int not null GENERATED BY DEFAULT AS IDENTITY ,
  NAME varchar(100) not null,
  CONSTRAINT genre_id PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS USERS(
  ID int not null GENERATED BY DEFAULT AS IDENTITY ,
  email varchar(100) not null,
  login varchar(100) not null,
  name varchar(100) not null,
  birthday date,
  CONSTRAINT user_id PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS FILM(
  ID int not null GENERATED BY DEFAULT AS IDENTITY ,
  name varchar(100) not null,
  description varchar(100) not null,
  releaseDate date,
  duration integer,
  rating_id integer REFERENCES rating (id),
  CONSTRAINT film_id PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS GENRE_FILM(
  film_id integer REFERENCES film(id) ON DELETE CASCADE,
  genre_id integer REFERENCES genre(id),
  CONSTRAINT genre_film_id PRIMARY KEY (film_id, genre_id)
);
CREATE TABLE IF NOT EXISTS LIKES(
  film_id integer REFERENCES film(id) ON DELETE CASCADE,
  user_id integer REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT likes_pk PRIMARY KEY (film_id, user_id)
);
CREATE TABLE IF NOT EXISTS FRIENDS(
  friend1_id integer REFERENCES users(id) ON DELETE CASCADE,
  friend2_id integer REFERENCES users(id) ON DELETE CASCADE,
  status integer not null,
  CONSTRAINT friends_pk PRIMARY KEY (friend1_id, friend2_id)
);

